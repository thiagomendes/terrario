function desenhoFerramenta(tipo: TipoFerramenta, cor: string, cor2: string) {
  return {
    paleta: { k: '#1d1610', c: CABO, '*': cor, '#': cor2 },
    linhas: FORMAS[tipo].map((l, y) =>
      [...l].map((ch, x) => (ch === '*' && (x + y) % 3 === 0 ? '#' : ch)).join(''),
    ),
  };
}

