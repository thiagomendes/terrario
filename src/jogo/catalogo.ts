let registrado = false;

/** Registra materiais, ferramentas e comidas (idempotente). */
export function registrarCatalogo(): void {
  if (registrado) return;
  registrado = true;
  for (const [id, d] of Object.entries(SIMPLES)) {
    registrarItem({
      id,
      nome: d.nome,
      tipo: d.tipo,
      pilha: 64,
      ...(d.comida ? { comida: { fome: d.comida[0], saturacao: d.comida[1] } } : {}),
    });
    registrarDesenho(id, { paleta: d.paleta, linhas: d.linhas });
  }
  const metais: [string, string, string, string, string][] = [
    ['cobre', 'Cobre', '#c46e3a', '#e08a55', '#ffc49a'],
    ['ferro', 'Ferro', '#cfab90', '#e2c4a8', '#ffffff'],
    ['ouro', 'Ouro', '#efc33a', '#ffe070', '#fff6c8'],
  ];
  for (const [id, nome, a, b, w] of metais) {
    registrarItem({ id: `${id}_bruto`, nome: `${nome} bruto`, tipo: 'material', pilha: 64 });
    registrarDesenho(`${id}_bruto`, bruto(a, b));
    registrarItem({
      id: `lingote_${id}`,
      nome: `Lingote de ${nome.toLowerCase()}`,
      tipo: 'material',
      pilha: 64,
    });
    registrarDesenho(`lingote_${id}`, lingote(a, b, w));
  }
  for (const n of NIVEIS) {
    for (const tipo of Object.keys(TIPOS) as TipoFerramenta[]) {
      const id = `${tipo}_${n.id}`;
      registrarItem({
        id,
        nome: `${TIPOS[tipo]} ${n.nome}`,
        tipo: 'ferramenta',
        pilha: 1,
        durabilidade: n.dur,
        ferramenta: {
          tipo,
          nivel: n.nivel,
          velocidade: n.vel,
          dano: tipo === 'espada' ? n.dano : Math.ceil(n.dano / 2),
        },
      });
      registrarDesenho(id, desenhoFerramenta(tipo, n.cor, n.cor2));
    }
  }
}
