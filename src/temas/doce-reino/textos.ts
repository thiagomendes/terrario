import type { TextosTema } from '../tipos';

/**
 * Ferramentas: colher (picareta), espátula (machado), concha (pá), pirulito (espada) e
 * garfinho (enxada).
 */
const NIVEIS = {
  madeira: 'de pau',
  pedra: 'de caramelo',
  cobre: 'de jujuba',
  ferro: 'de coco',
  cristal: 'de bala-estrela',
} as const;
const PIRULITOS: Record<keyof typeof NIVEIS, string> = {
  madeira: 'Palito de pirulito',
  pedra: 'Pirulito de caramelo',
  cobre: 'Pirulito de jujuba',
  ferro: 'Pirulito de coco',
  cristal: 'Pirulito-estrela',
};

function ferramentas(): Record<string, string> {
  const r: Record<string, string> = {};
  for (const [nivel, de] of Object.entries(NIVEIS) as [keyof typeof NIVEIS, string][]) {
    r[`picareta_${nivel}`] = `Colher ${de}`;
    r[`machado_${nivel}`] = `Espátula ${de}`;
    r[`pa_${nivel}`] = `Concha ${de}`;
    r[`espada_${nivel}`] = PIRULITOS[nivel];
    r[`enxada_${nivel}`] = `Garfinho ${de}`;
  }
  return r;
}

