/** Ferramentas da roça: picareta, machado, pá, facão (espada) e enxada nos 5 níveis. */
const NIVEIS = {
  madeira: 'de pau',
  pedra: 'de pedra',
  cobre: 'de cobre',
  ferro: 'de ferro',
  cristal: 'de cristal',
} as const;
const FACOES: Record<keyof typeof NIVEIS, string> = {
  madeira: 'Facão de pau',
  pedra: 'Facão de pedra',
  cobre: 'Facão de cobre',
  ferro: 'Facão de ferro',
  cristal: 'Facão de cristal',
};

function ferramentas(): Record<string, string> {
  const r: Record<string, string> = {};
  for (const [nivel, de] of Object.entries(NIVEIS) as [keyof typeof NIVEIS, string][]) {
    r[`picareta_${nivel}`] = `Picareta ${de}`;
    r[`machado_${nivel}`] = `Machadinha ${de}`;
    r[`pa_${nivel}`] = `Pá ${de}`;
    r[`espada_${nivel}`] = FACOES[nivel];
    r[`enxada_${nivel}`] = `Enxada ${de}`;
  }
  return r;
}

